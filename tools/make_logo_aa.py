"""Generate native-size 4-bit coverage masks from the pinned SVG; keep OS icons unchanged."""
from pathlib import Path
from io import BytesIO
import sys
from PIL import Image
try: import cairosvg
except ImportError:
 sys.path.insert(0,'/workspace/casio-tools/python');import cairosvg
root=Path(__file__).resolve().parents[1]
svg=(root/'assets/openai.svg').read_bytes()
rows=['/* Generated by tools/make_logo_aa.py from assets/openai.svg. See docs/LOGO-SOURCE.md. */','#ifndef CHATGPT_LOGO_AA_H','#define CHATGPT_LOGO_AA_H','#include <stdint.h>']
for size in (16,24,40,48,56,64):
 im=Image.open(BytesIO(cairosvg.svg2png(bytestring=svg,output_width=size*8,output_height=size*8))).convert('RGBA').getchannel('A').resize((size,size),Image.Resampling.LANCZOS)
 alpha=[(im.getpixel((x,y))*15+127)//255 for y in range(size) for x in range(size)]
 packed=[alpha[i]*16+alpha[i+1] for i in range(0,len(alpha),2)]
 rows.append(f'static const uint8_t logo_aa{size}[]={{')
 rows.extend(','.join(f'0x{v:02x}' for v in packed[i:i+24])+',' for i in range(0,len(packed),24))
 rows.append('};')
rows+=['#endif'];(root/'casio/logo_aa.h').write_text('\n'.join(rows)+'\n')
print('Generated 4-bit antialiased logos: 16, 24, 40, 48, 56, 64 pixels; native menu icons untouched.')
